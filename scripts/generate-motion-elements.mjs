import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

// Explicit HTML surface: content elements, not document metadata, custom tags or SVG.
const tags =
	`a abbr address area article aside audio b bdi bdo blockquote br button canvas caption cite code col colgroup data datalist dd del details dfn dialog div dl dt em embed fieldset figcaption figure footer form h1 h2 h3 h4 h5 h6 header hgroup hr i iframe img input ins kbd label legend li main map mark menu meter nav object ol optgroup option output p picture pre progress q rp rt ruby s samp search section select small source span strong sub summary sup table tbody td template textarea tfoot th thead time tr track u ul var video wbr`.split(
		' '
	);
const voidTags = new Set('area br col embed hr img input source track wbr'.split(' '));
const root = new URL('../src/lib/motion/elements/', import.meta.url);
const check = process.argv.includes('--check');
const config = await resolveConfig(fileURLToPath(new URL('../.prettierrc', import.meta.url)));
const generated = new Map();
const banner = '<!-- Generated by scripts/generate-motion-elements.mjs. Edit the generator. -->';

function nativeComponent(
	tag,
	{ type = `MotionElementProps<'${tag}'>`, generics = '', props = '', attributes = '' } = {}
) {
	const children = !voidTags.has(tag) && tag !== 'textarea';
	const markup = `<${tag}\n\t{...nativeAttributes}\n\t{...binding.props}\n\tstyle={\`${"${typeof style === 'string' ? style : ''};${binding.props.style}"}\`}\n\ttransition:motionTransition|global\n\t{@attach forwardRef}${attributes ? `\n\t${attributes}` : ''}${voidTags.has(tag) ? '\n/>' : `\n>${children ? '\n\t{@render children?.()}\n' : ''}</${tag}>`}`;
	return `${banner}
<script lang="ts"${generics ? ` generics="${generics}"` : ''}>
 import { createComponentMotion } from '../component-motion.js';
 import { componentMotionOptions, nativeComponentProps } from '../component-props.js';
 import type { ${type.split('<')[0]} } from './types.js';
 let {
  motion = {},
  ref = $bindable(),
  style,${children ? '\n  children,' : ''}${props}
  ...attributes
 }: ${type} = $props();
 const binding = createComponentMotion(() => componentMotionOptions(motion, attributes, style));
 const nativeAttributes = $derived(nativeComponentProps(attributes));
 const motionTransition = binding.transition;
 function forwardRef(node: HTMLElement) {
  ref = node as HTMLElementTagNameMap['${tag}'];
  return () => { if (ref === node) ref = null; };
 }
</script>

${tag === 'figcaption' ? '<!-- svelte-ignore a11y_figcaption_parent (The consumer supplies the figure parent.) -->\n' : ''}${markup}
`;
}

for (const tag of tags) {
	const type =
		tag === 'textarea'
			? 'MotionTextareaProps'
			: tag === 'details'
				? 'MotionDetailsProps'
				: undefined;
	const props =
		tag === 'textarea'
			? '\n  value = $bindable(),'
			: tag === 'details'
				? '\n  open = $bindable(),'
				: '';
	const attributes = tag === 'textarea' ? 'bind:value' : tag === 'details' ? 'bind:open' : '';
	if (tag !== 'input' && tag !== 'select')
		generated.set(`${tag}.svelte`, nativeComponent(tag, { type, props, attributes }));
}

const inputBranches = [
	{
		name: 'Checkbox',
		props: '\n  value,\n  checked = $bindable(),\n  indeterminate = $bindable(),',
		attributes: 'type="checkbox" {value} bind:checked bind:indeterminate'
	},
	{ name: 'File', props: '\n  files = $bindable(),', attributes: 'type="file" bind:files' },
	{ name: 'Radio', props: '\n  value,\n  checked,', attributes: 'type="radio" {value} {checked}' },
	{ name: 'Value', props: '\n  type,\n  value = $bindable(),', attributes: '{type} bind:value' }
];
for (const { name, props, attributes } of inputBranches) {
	generated.set(
		`Input${name}.svelte`,
		nativeComponent('input', { type: 'NativeInputProps', props, attributes })
	);
}
generated.set(
	'input.svelte',
	`${banner}
<script lang="ts" generics="Type extends HTMLInputTypeAttribute | null = 'text'">
 import type { HTMLInputTypeAttribute } from 'svelte/elements';
 import type { MotionInputProps } from './types.js';
 ${inputBranches.map(({ name }) => `import Input${name} from './Input${name}.svelte';`).join('\n ')}
 let { type = 'text' as Type, value = $bindable(), checked = $bindable(), indeterminate = $bindable(), files = $bindable(), ref = $bindable(), ...attributes }: MotionInputProps<Type> = $props();
</script>

{#if type === 'checkbox'}
 <InputCheckbox {...attributes} {value} bind:checked bind:indeterminate bind:ref />
{:else if type === 'file'}
 <InputFile {...attributes} bind:files bind:ref />
{:else if type === 'radio'}
 <InputRadio {...attributes} {value} {checked} bind:ref />
{:else}
 <InputValue {...attributes} {type} bind:value bind:ref />
{/if}
`
);
for (const multiple of [false, true]) {
	generated.set(
		`Select${multiple ? 'Multiple' : 'Single'}.svelte`,
		nativeComponent('select', {
			type: 'MotionSelectProps<Value>',
			generics: 'Value = unknown',
			props: '\n  value = $bindable(),',
			attributes: `${multiple ? 'multiple ' : ''}bind:value`
		})
	);
}
generated.set(
	'select.svelte',
	`${banner}
<script lang="ts" generics="Value = unknown">
 import type { MotionSelectProps } from './types.js';
 import SelectSingle from './SelectSingle.svelte';
 import SelectMultiple from './SelectMultiple.svelte';
 let { multiple, value = $bindable(), ref = $bindable(), ...attributes }: MotionSelectProps<Value> = $props();
</script>

{#if multiple}
 <SelectMultiple {...attributes} bind:value bind:ref />
{:else}
 <SelectSingle {...attributes} bind:value bind:ref />
{/if}
`
);
generated.set(
	'index.ts',
	'// Generated by scripts/generate-motion-elements.mjs. Edit the generator.\n' +
		tags.map((tag) => `export { default as ${tag} } from './${tag}.svelte';`).join('\n') +
		'\n'
);
if (!check) await mkdir(root, { recursive: true });
for (const name of await readdir(root)) {
	if (name.endsWith('.svelte') && !generated.has(name)) {
		if (check) throw new Error(`Unexpected generated motion element: ${name}`);
		await unlink(new URL(name, root));
	}
}
for (const [name, source] of generated) {
	const url = new URL(name, root);
	const formatted = await format(source, { ...config, filepath: fileURLToPath(url) });
	if (check) {
		if ((await readFile(url, 'utf8').catch(() => '')) !== formatted)
			throw new Error(
				`Generated motion element is stale: ${name}. Run node scripts/generate-motion-elements.mjs.`
			);
	} else await writeFile(url, formatted);
}
console.log(`${check ? 'Checked' : 'Generated'} ${tags.length} motion elements.`);
